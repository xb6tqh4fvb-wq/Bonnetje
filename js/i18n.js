export const UI_LANGS = ['nl', 'en'];
const LOCALES = { nl: 'nl-NL', en: 'en-IE' };

let lang = (() => {
  try {
    const saved = localStorage.getItem(KEY);
    if (UI_LANGS.includes(saved)) return saved;
  } catch {}
  const nav = (globalThis.navigator?.language || 'nl').slice(0, 2);
  return nav === 'nl' ? 'nl' : nav === 'en' ? 'en' : 'nl';
})();
setNumberLocale(LOCALES[lang]);

export const getLang = () => lang;

export function setLang(l) {
  if (!UI_LANGS.includes(l)) return;
  lang = l;
  setNumberLocale(LOCALES[l]);
  try {
    localStorage.setItem(KEY, l);
  } catch {}
  document.documentElement.lang = l;
}

export function t(key, vars = {}) {
  const s = STR[lang][key] ?? STR.nl[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Datum: DD-MM-JJJJ (nl) of DD/MM/YYYY (en). */
export function fmtDate(ts, withTime = true) {
  const d = new Date(ts);
  const p = (n) => String(n).padStart(2, '0');
  const sep = lang === 'en' ? '/' : '-';
  const date = [p(d.getDate()), p(d.getMonth() + 1), d.getFullYear()].join(sep);
  return withTime ? `${date} ${p(d.getHours())}:${p(d.getMinutes())}` : date;
}
