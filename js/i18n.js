export function t(lang, key, vars = {}) {
  const dict = STRINGS[lang] || STRINGS.nl;
  let val = dict[key] ?? STRINGS.nl[key] ?? key;
  if (typeof val === 'string') {
    for (const [k, v] of Object.entries(vars)) {
      val = val.replaceAll(`{${k}}`, String(v));
    }
  }
  return val;
}
